-- On which dates were the most orders placed?
SELECT 
    STR_TO_DATE(order_date, '%Y-%m-%d') AS order_date,
    COUNT(ord_id) AS total_orders
FROM orders
GROUP BY 
    STR_TO_DATE(order_date, '%Y-%m-%d')
ORDER BY total_orders DESC;

-- What are the monthly trends in order volume and revenue?
SELECT 
    DATE_FORMAT(
        STR_TO_DATE(o.order_date, '%Y-%m-%d'),
        '%Y-%m'
    ) AS month,
    COUNT(DISTINCT o.ord_id) AS order_volume,
    SUM(od.total_price) AS total_revenue
FROM orders o
JOIN order_details od
    ON o.ord_id = od.ord_id
GROUP BY 
    DATE_FORMAT(
        STR_TO_DATE(o.order_date, '%Y-%m-%d'),
        '%Y-%m'
    )
ORDER BY month;

-- How do order patterns vary across weekdays and weekends?
SELECT 
    CASE
        WHEN DAYOFWEEK(
            STR_TO_DATE(order_date, '%Y-%m-%d')
        ) IN (1, 7) THEN 'Weekend'
        ELSE 'Weekday'
    END AS day_type,
    COUNT(ord_id) AS total_orders
FROM orders
GROUP BY day_type;

