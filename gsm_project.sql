-- What is the total sales value processed by each employee?
SELECT 
    e.emp_id,
    e.emp_name,
    SUM(od.total_price) AS total_sales
FROM employees e
JOIN orders o
    ON e.emp_id = o.emp_id
JOIN order_details od
    ON o.ord_id = od.ord_id
GROUP BY 
    e.emp_id,
    e.emp_name
ORDER BY total_sales DESC;

-- What is the average order value handled per employee?
SELECT 
    e.emp_id,
    e.emp_name,
    AVG(order_total) AS average_order_value
FROM employees e
JOIN (
    SELECT 
        o.ord_id,
        o.emp_id,
        SUM(od.total_price) AS order_total
    FROM orders o
    JOIN order_details od
        ON o.ord_id = od.ord_id
    GROUP BY 
        o.ord_id,
        o.emp_id
) AS order_values
    ON e.emp_id = order_values.emp_id
GROUP BY 
    e.emp_id,
    e.emp_name
ORDER BY average_order_value DESC;

-- Order Details Deep Dive
-- What is the relationship between quantity ordered and total price?
SELECT 
    quantity,
    COUNT(*) AS number_of_items,
    SUM(total_price) AS total_sales
FROM order_details
